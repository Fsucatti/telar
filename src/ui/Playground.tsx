import { AlertCircle, Check, ChevronRight, Eraser, Loader2, Minus, Send, Sparkles, Square, Wrench, X } from "lucide-react";
import { useEffect, useMemo, useRef, useState } from "react";
import { validateFlow } from "../engine/run";
import { startRun, stopRun } from "../state/runner";
import { useCurrentAgent, useStore, type ChatEntry, type RunStepView } from "../state/store";
import { Markdown } from "./common";

function StepIcon({ step }: { step: RunStepView }) {
  if (step.status === "running") return <Loader2 size={13} className="spin status-running" />;
  if (step.status === "done") return <Check size={13} className="status-done" />;
  if (step.status === "error") return <X size={13} className="status-error" />;
  return <Minus size={13} className="muted" />;
}

function Steps({ steps, defaultOpen }: { steps: RunStepView[]; defaultOpen: boolean }) {
  const total = steps.reduce((sum, step) => sum + (step.ms ?? 0), 0);
  return (
    <details className="steps" open={defaultOpen}>
      <summary>
        <ChevronRight size={13} className="steps-chevron" />
        {steps.length} steps{total > 0 ? ` · ${(total / 1000).toFixed(1)}s` : ""}
      </summary>
      <ol>
        {steps.map((step) => (
          <li key={step.nodeId}>
            <StepIcon step={step} />
            <span className="grow">
              {step.title}
              {step.status === "skipped" && <span className="muted"> (path not taken)</span>}
              {step.tools.map((tool, index) => (
                <span className="chip chip-pink" key={index}><Wrench size={10} /> {tool}</span>
              ))}
            </span>
            {step.ms !== undefined && <span className="muted small">{(step.ms / 1000).toFixed(1)}s</span>}
          </li>
        ))}
      </ol>
    </details>
  );
}

function AgentMessage({ entry }: { entry: ChatEntry }) {
  const canSimulate = entry.error && entry.error.code !== "stopped" && !entry.simulated && entry.input;
  return (
    <div className="message message-agent">
      {entry.simulated && <span className="chip chip-orange">Simulated: no AI used</span>}
      {entry.steps.length > 0 && <Steps steps={entry.steps} defaultOpen={Boolean(entry.running)} />}
      {entry.running && !entry.live && <p className="muted small thinking">Working…</p>}
      {entry.running && entry.live && <Markdown text={entry.live} />}
      {entry.images.map((image, index) => (
        <img className="message-image" key={index} src={image} alt="Generated by the agent" />
      ))}
      {entry.text && <Markdown text={entry.text} />}
      {!entry.running && !entry.text && !entry.error && entry.images.length === 0 && (
        <p className="muted small">The agent finished without any text.</p>
      )}
      {entry.error && (
        <div className={`notice ${entry.error.code === "stopped" ? "" : "notice-error"}`} role="alert">
          <p>{entry.error.message}</p>
          {canSimulate && (
            <button className="button" onClick={() => startRun(entry.input as string, true)}>
              Run with simulated answers
            </button>
          )}
        </div>
      )}
    </div>
  );
}

export function Playground() {
  const agent = useCurrentAgent();
  const chat = useStore((state) => state.chat);
  const isRunning = useStore((state) => state.isRunning);
  const simulated = useStore((state) => state.simulated);
  const { setPanel, clearChat, setSimulated } = useStore.getState();
  const [text, setText] = useState("");
  const end = useRef<HTMLDivElement>(null);

  const flow = agent?.flow;
  const blockers = useMemo(() => (flow ? validateFlow(flow).filter((issue) => issue.severity === "error") : []), [flow]);

  useEffect(() => {
    end.current?.scrollIntoView?.({ block: "end" });
  }, [chat]);

  if (!agent) return null;

  const send = (message: string) => {
    const clean = message.trim();
    if (!clean || isRunning || blockers.length > 0) return;
    setText("");
    void startRun(clean, simulated);
  };

  return (
    <aside className="side-panel" aria-label="Playground">
      <div className="side-panel-head">
        <strong className="panel-title-static">Playground</strong>
        <button className="icon-button" aria-label="Clear conversation" title="Clear conversation" disabled={isRunning || chat.length === 0} onClick={clearChat}>
          <Eraser size={16} />
        </button>
        <button className="icon-button" aria-label="Close playground" onClick={() => setPanel(null)}>
          <X size={18} />
        </button>
      </div>

      <div className="chat">
        {blockers.length > 0 && (
          <div className="notice notice-error" role="alert">
            <AlertCircle size={15} />
            <ul>
              {blockers.map((issue) => <li key={issue.message}>{issue.message}</li>)}
            </ul>
          </div>
        )}

        {chat.length === 0 ? (
          <div className="chat-empty">
            <Sparkles size={26} className="accent" />
            <h3>Test this agent</h3>
            <p className="muted">{agent.description || "Ask something, or pick a prompt to get started."}</p>
            <div className="suggestions">
              {agent.suggestions.map((suggestion) => (
                <button key={suggestion} disabled={blockers.length > 0} onClick={() => send(suggestion)}>
                  <Sparkles size={13} /> {suggestion}
                </button>
              ))}
            </div>
          </div>
        ) : (
          chat.map((entry) =>
            entry.role === "user" ? (
              <div className="message message-user" key={entry.id}>{entry.text}</div>
            ) : (
              <AgentMessage entry={entry} key={entry.id} />
            ),
          )
        )}
        <div ref={end} />
      </div>

      <div className="composer">
        <div className="composer-box">
          <textarea
            rows={1}
            placeholder="Ask anything…"
            aria-label="Message"
            value={text}
            onChange={(event) => setText(event.target.value)}
            onKeyDown={(event) => {
              if (event.key === "Enter" && !event.shiftKey) {
                event.preventDefault();
                send(text);
              }
            }}
          />
          {isRunning ? (
            <button className="send-button" aria-label="Stop" onClick={stopRun}><Square size={14} /></button>
          ) : (
            <button className="send-button" aria-label="Send" disabled={!text.trim() || blockers.length > 0} onClick={() => send(text)}><Send size={14} /></button>
          )}
        </div>
        <label className="simulate-toggle">
          <input type="checkbox" checked={simulated} onChange={(event) => setSimulated(event.target.checked)} />
          Simulated answers (no AI, uses no allowance)
        </label>
      </div>
    </aside>
  );
}
